from uuid import UUID

from pydantic import BaseModel, Field, field_validator, model_validator

from app.schemas.workouts import MAX_EXERCISES, Name


class WorkoutSchemeExerciseRequest(BaseModel):
    exercise_id: int = Field(
        ...,
        description="The ID of the exercise",
        examples=[12]
    )
    index: int = Field(
        ...,
        ge=0,
        description="Order of the exercise within the scheme",
        examples=[0]
    )


def _check_consecutive_indexes(exercises: list[WorkoutSchemeExerciseRequest]) -> None:
    if sorted(ex.index for ex in exercises) != list(range(len(exercises))):
        raise ValueError("Exercise indexes must be unique and consecutive, starting at 0.")


class CreateWorkoutSchemeRequest(BaseModel):
    client_uuid: UUID | None = Field(
        default=None,
        description="Generated by the client once per created object. If an object with this UUID already exists, it is returned instead of creating it again.",
        examples=["3f2b8c1e-5d4a-4c6b-9a7e-1f0d2c3b4a59"]
    )
    name: Name = Field(
        ...,
        description="Name of the workout scheme, leading and trailing whitespace is removed",
        examples=["Push Day"]
    )
    exercises: list[WorkoutSchemeExerciseRequest] = Field(
        ...,
        max_length=MAX_EXERCISES,
        description="Exercises of the scheme. Their indexes must be exactly 0..n-1."
    )

    @model_validator(mode="after")
    def indexes_are_consecutive(self):
        _check_consecutive_indexes(self.exercises)
        return self


class UpdateWorkoutSchemeRequest(BaseModel):
    name: Name | None = Field(
        default=None,
        description="Name of the workout scheme, leading and trailing whitespace is removed",
        examples=["Push Day"]
    )
    exercises: list[WorkoutSchemeExerciseRequest] | None = Field(
        default=None,
        max_length=MAX_EXERCISES,
        description="Complete new list of exercises, replacing all existing ones. Their indexes must be exactly 0..n-1."
    )

    @field_validator("name", "exercises")
    @classmethod
    def not_null(cls, value):
        # Only runs for fields that were sent. They may be omitted, but not explicitly set to null.
        if value is None:
            raise ValueError("Field cannot be null.")
        return value

    @model_validator(mode="after")
    def indexes_are_consecutive(self):
        if self.exercises is not None:
            _check_consecutive_indexes(self.exercises)
        return self


class WorkoutSchemeExerciseResponse(WorkoutSchemeExerciseRequest):
    id: int = Field(
        ...,
        description="Unique identifier for the workout scheme exercise",
        examples=[1]
    )


class WorkoutSchemeResponse(BaseModel):
    id: int = Field(
        ...,
        description="Unique identifier for the workout scheme",
        examples=[1]
    )
    client_uuid: UUID | None = Field(
        default=None,
        description="The UUID the client sent when creating the object",
        examples=["3f2b8c1e-5d4a-4c6b-9a7e-1f0d2c3b4a59"]
    )
    name: str = Field(
        ...,
        max_length=25,
        description="Name of the workout scheme",
        examples=["Push Day"]
    )
    last_performed: str | None = Field(
        default=None,
        description="When a workout based on this scheme was last started, in ISO 8601 format (UTC)",
        examples=["2024-06-01T18:30:00+00:00"]
    )
    exercises: list[WorkoutSchemeExerciseResponse] = Field(
        ...,
        description="Exercises of the scheme, ordered by index"
    )


class WorkoutSchemeListResponse(BaseModel):
    schemes: list[WorkoutSchemeResponse] = Field(
        ...,
        description="All workout schemes of the current user"
    )
    sync_time: str = Field(
        ...,
        description="Database timestamp of this response in ISO 8601 format. Pass it as last_sync_time to /workout-schemes/delta for the next sync.",
        examples=["2024-06-01T18:30:00.123456+00:00"]
    )


class SingleWorkoutSchemeDeltaResponse(WorkoutSchemeResponse):
    """
    A changed workout scheme. Unless it was deleted, it always contains the complete list of its exercises.
    action: 0: created, 1: updated, 2: deleted
    """
    action: int = Field(
        ...,
        description="An integer representing the type of change: 0 for created, 1 for updated, 2 for deleted",
        examples=[0, 1, 2]
    )

    # Override to allow None values when action is 2 (deleted)
    name: str | None = Field(default=None, max_length=25)  # type: ignore[assignment]
    exercises: list[WorkoutSchemeExerciseResponse] = Field(default=[])


class WorkoutSchemeDeltaResponse(BaseModel):
    """
    Clients should treat created (0) and updated (1) as an upsert (replacing the complete exercise list)
    and ignore deletions (2) of unknown IDs, because a change can be delivered more than once.
    """
    updates: list[SingleWorkoutSchemeDeltaResponse] = Field(
        ...,
        description="List of workout schemes that have been created, updated, or deleted since the last sync"
    )
    sync_time: str = Field(
        ...,
        description="Database timestamp of this response in ISO 8601 format. Pass it as last_sync_time for the next sync.",
        examples=["2024-06-01T18:30:00.123456+00:00"]
    )
