from typing import Annotated, Literal
from uuid import UUID

from pydantic import AwareDatetime, BaseModel, Field, StringConstraints, field_validator, model_validator

# The limits match the column types of the workout_exercise table, so that invalid
# values are rejected with a 422 instead of failing in the database.

MAX_SETS = 100                  # Per workout exercise
MAX_EXERCISES = 100             # Per workout

# Names of workouts and workout schemes: leading and trailing whitespace is removed, the rest can't be empty
Name = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=25)]

RepsValue = Annotated[int, Field(ge=0, le=9999)]
WeightValue = Annotated[float, Field(ge=-9999.9, le=9999.9, allow_inf_nan=False)]                  # NUMERIC(5,1), negative for assisted exercises
TimeValue = Annotated[int, Field(ge=0, le=86400)]                                                  # Seconds, max. 24 hours per set
IntensityValue = Annotated[float, Field(ge=-9999.99, le=9999.99, allow_inf_nan=False)]             # NUMERIC(6,2), negative for e.g. a declined treadmill
DistanceValue = Annotated[float, Field(ge=0, le=999999.999, allow_inf_nan=False)]                  # NUMERIC(9,3)


class WorkoutExerciseRequest(BaseModel):
    client_uuid: UUID | None = Field(
        default=None,
        description="Generated by the client once per created object. If an object with this UUID already exists, it is returned instead of creating it again.",
        examples=["3f2b8c1e-5d4a-4c6b-9a7e-1f0d2c3b4a59"]
    )
    exercise_id: int = Field(
        ...,
        description="The ID of the exercise being performed",
        examples=[12]
    )
    unilateral: bool = Field(
        ...,
        description="Whether the exercise is performed one side at a time",
        examples=[False]
    )
    index: int = Field(
        ...,
        ge=0,
        description="Order in which the exercise is performed within the workout",
        examples=[0]
    )

    reps: list[RepsValue] | None = Field(
        default=None,
        max_length=MAX_SETS,
        description="Array of reps per set, null if the exercise does not track it",
        examples=[[12, 10, 8]]
    )
    weights: list[WeightValue] | None = Field(
        default=None,
        max_length=MAX_SETS,
        description="Array of weights per set, null if the exercise does not track it",
        examples=[[12.5, 12.0, 10.0]]
    )
    time: list[TimeValue] | None = Field(
        default=None,
        max_length=MAX_SETS,
        description="Array of time/duration per set in seconds, null if the exercise does not track it",
        examples=[[30, 60, 30]]
    )
    intensity: list[IntensityValue] | None = Field(
        default=None,
        max_length=MAX_SETS,
        description="Array of intensities per set for example resistance level of a machine, null if the exercise does not track it",
        examples=[[8.5, 135.0, 9.5]]
    )
    distance: list[DistanceValue] | None = Field(
        default=None,
        max_length=MAX_SETS,
        description="Array of distances per set in meters, null if the exercise does not track it",
        examples=[[7.42, 1000.0, 1500.0]]
    )


class CreateWorkoutRequest(BaseModel):
    client_uuid: UUID | None = Field(
        default=None,
        description="Generated by the client once per created object. If an object with this UUID already exists, it is returned instead of creating it again.",
        examples=["3f2b8c1e-5d4a-4c6b-9a7e-1f0d2c3b4a59"]
    )
    name: Name = Field(
        ...,
        description="Name of the workout session, leading and trailing whitespace is removed",
        examples=["Upper Body Strength"]
    )
    date: AwareDatetime = Field(
        ...,
        description="Date and time of the workout in ISO 8601 format including a timezone",
        examples=["2024-06-01T18:30:00Z"]
    )
    duration: int = Field(
        ...,
        ge=0,
        le=1440,
        description="Duration of the workout in minutes",
        examples=[60]
    )
    in_progress: bool = Field(
        ...,
        description="Indicates if the workout is currently in progress. A user can have several workouts in progress, the clients try to avoid it.",
        examples=[False]
    )
    exercises: list[WorkoutExerciseRequest] = Field(
        ...,
        max_length=MAX_EXERCISES,
        description="List of exercises included in the workout. Their indexes must be exactly 0..n-1."
    )

    @model_validator(mode="after")
    def indexes_are_consecutive(self):
        if sorted(ex.index for ex in self.exercises) != list(range(len(self.exercises))):
            raise ValueError("Exercise indexes must be unique and consecutive, starting at 0.")
        return self

    @model_validator(mode="after")
    def client_uuids_are_unique(self):
        client_uuids = [ex.client_uuid for ex in self.exercises if ex.client_uuid is not None]
        if len(client_uuids) != len(set(client_uuids)):
            raise ValueError("The client UUIDs of the exercises must be unique.")
        return self


class CreateWorkoutExerciseChange(WorkoutExerciseRequest):
    op: Literal["create"] = Field(
        ...,
        description="Inserts a new workout exercise into the workout. If the workout already contains an exercise with the same client UUID, nothing is changed.",
        examples=["create"]
    )
    index: int = Field(
        ...,
        ge=0,
        description="Position at which the exercise is inserted. Exercises at or after this index are moved back by one. Must be at most the current number of exercises.",
        examples=[0]
    )


