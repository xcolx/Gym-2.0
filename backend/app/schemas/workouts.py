class WorkoutListResponse(BaseModel):
    workouts: list[WorkoutResponse] = Field(
        ...,
        description="All workouts of the current user"
    )
    sync_time: str = Field(
        ...,
        description="Database timestamp of this response in ISO 8601 format. Pass it as last_sync_time to /workouts/delta for the next sync.",
        examples=["2024-06-01T18:30:00.123456+00:00"]
    )


class SingleWorkoutDeltaResponse(WorkoutResponse):
    """
    action: 0: created, 1: updated, 2: deleted
    """
    action: int = Field(
        ...,
        description="An integer representing the type of change: 0 for created, 1 for updated, 2 for deleted",
        examples=[0, 1, 2]
    )

    # Override to allow None values when action is 2 (deleted)
    name: str | None = Field(default=None, max_length=25)  # type: ignore[assignment]
    date: str | None = Field(default=None)  # type: ignore[assignment]
    duration: int | None = Field(default=None)  # type: ignore[assignment]
    in_progress: bool | None = Field(default=None)  # type: ignore[assignment]
    exercises: list[WorkoutExerciseResponse] = Field(default=[])

class WorkoutDeltaResponse(BaseModel):
    """
    Clients should treat created (0) and updated (1) as an upsert and ignore deletions (2) of unknown IDs,
    because a change can be delivered more than once.
    """
    updates: list[SingleWorkoutDeltaResponse] = Field(
        ...,
        description="List of workouts that have been created, updated, or deleted since the last sync"
    )
    sync_time: str = Field(
        ...,
        description="Database timestamp of this response in ISO 8601 format. Pass it as last_sync_time for the next sync.",
        examples=["2024-06-01T18:30:00.123456+00:00"]
    )
