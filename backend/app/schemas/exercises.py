from typing import Annotated
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, model_validator


class CreateExerciseRequest(BaseModel):
    """
    Sent as multipart/form-data together with the image files.
    The muscle ID lists and the aliases are sent as repeated form fields.
    """
    client_uuid: UUID | None = Field(
        default=None,
        description="Generated by the client once per created object. If an object with this UUID already exists, it is returned instead of creating it again.",
        examples=["3f2b8c1e-5d4a-4c6b-9a7e-1f0d2c3b4a59"]
    )
    name: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=50)] = Field(
        ...,
        description="Name of the exercise, leading and trailing whitespace is removed",
        examples=["Barbell Bench Press"]
    )
    description: Annotated[str, StringConstraints(strip_whitespace=True, max_length=1000)] | None = Field(
        None,
        description="Detailed instructions or description of the exercise, leading and trailing whitespace is removed",
        examples=["Lie back on a flat bench. Grip the barbell slightly wider than shoulder-width..."]
    )
    aliases: list[Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=50)]] = Field(
        default_factory=list,
        max_length=20,
        description="Other names of the exercise, only used by the search of the clients, leading and trailing whitespace is removed. "
                    "Duplicates and the name itself are ignored, regardless of case.",
        examples=[["Military Press", "Overhead Press"]]
    )
    muscle_group_id: int = Field(
        ...,
        description="Foreign key ID of the main muscle group targeted",
        examples=[5]
    )
    equipment_id: int = Field(
        ...,
        description="Foreign key ID of the required equipment",
        examples=[2]
    )

    primary_muscle_ids: list[int] = Field(
        default_factory=list,
        description="List of specific muscle IDs targeted as primary movers",
        examples=[[12, 15]]
    )
    secondary_muscle_ids: list[int] = Field(
        default_factory=list,
        description="List of specific muscle IDs targeted as secondary/stabilizer muscles",
        examples=[[3, 8]]
    )

    reps: bool = Field(
        ...,
        description="True if the exercise tracks repetition counts",
        examples=[True]
    )
    weights: bool = Field(
        ...,
        description="True if the exercise tracks weight/resistance",
        examples=[True]
    )
    time: bool = Field(
        ...,
        description="True if the exercise tracks duration",
        examples=[False]
    )
    intensity: bool = Field(
        ...,
        description="True if the exercise tracks intensity (e.g., RPE)",
        examples=[False]
    )
    distance: bool = Field(
        ...,
        description="True if the exercise tracks distance",
        examples=[False]
    )

    @model_validator(mode="after")
    def check_tracks_metric(self):
        if not (self.reps or self.weights or self.time or self.intensity or self.distance):
            raise ValueError("An exercise has to track at least one metric (reps, weights, time, intensity or distance).")
        return self

    @model_validator(mode="after")
    def remove_duplicate_aliases(self):
        seen = {self.name.casefold()}
        aliases = []
        for alias in self.aliases:
            if alias.casefold() not in seen:
                seen.add(alias.casefold())
                aliases.append(alias)
        self.aliases = aliases
        return self


class ExerciseResponse(BaseModel):
    id: int = Field(
        ...,
        description="The unique identifier for the exercise",
        examples=[123]
    )
    client_uuid: UUID | None = Field(
        default=None,
        description="The UUID the client sent when creating the exercise, only included for exercises of the current user",
        examples=["3f2b8c1e-5d4a-4c6b-9a7e-1f0d2c3b4a59"]
    )
    name: str = Field(
        ...,
        max_length=50,
        description="Name of the exercise",
        examples=["Barbell Bench Press", "Dumbbell Bicep Curl"]
    )
    description: str | None = Field(
        None,
        description="Detailed instructions or description of the exercise",
        examples=["Lie back on a bench and press the barbell upwards until your arms are fully extended, then lower it back down to chest level."]
    )
    aliases: list[str] = Field(
        default_factory=list,
        description="Other names of the exercise, only used by the search of the clients and not meant to be shown",
        examples=[["Military Press", "Overhead Press"], []]
    )
    image_urls: list[str] = Field(
        default_factory=list,
        description="Image hashes of the instructional images in the order they are shown, e.g. one per keyframe of the movement (served by GET /v1/images/{hash})",
        examples=[["3fa9c1d2e4b5a6978877665544332211ffeeddccbbaa99887766554433221100"], []]
    )
    muscle_group_id: int = Field(
        ...,
        description="Foreign key ID of the main muscle group targeted",
        examples=[5]
    )
    equipment_id: int = Field(
        ...,
        description="Foreign key ID of the required equipment",
        examples=[2]
    )
    verified: bool = Field(
        ...,
        description="Whether the exercise has been verified by an admin",
        examples=[True, False]
    )

    reps: bool = Field(
        ...,
        description="True if the exercise tracks repetition counts",
        examples=[True, False]
    )
    weights: bool = Field(
        ...,
        description="True if the exercise tracks weight/resistance",
        examples=[True, False]
    )
    time: bool = Field(
        ...,
        description="True if the exercise tracks duration",
        examples=[True, False]
    )
    intensity: bool = Field(
        ...,
        description="True if the exercise tracks intensity (e.g., RPE)",
        examples=[True, False]
    )
    distance: bool = Field(
        ...,
        description="True if the exercise tracks distance",
        examples=[True, False]
    )

    primary_muscle_ids: list[int] = Field(
        default_factory=list,
        description="List of muscle IDs where is_primary is True",
        examples=[[1, 2], [5], []]
    )
    secondary_muscle_ids: list[int] = Field(
        default_factory=list,
        description="List of muscle IDs where is_primary is False",
        examples=[[3, 4], [6, 7], []]
    )


class EquipmentResponse(BaseModel):
    id: int = Field(
        ...,
        description="The unique identifier for the equipment",
        examples=[1]
    )
    name: str = Field(
        ...,
        max_length=20,
        description="The name of the equipment (e.g., Barbell, Dumbbell)",
        examples=["Barbell", "Dumbbell", "Kettlebell"]
    )

    model_config = ConfigDict(from_attributes=True)


class MuscleGroupResponse(BaseModel):
    id: int = Field(
        ...,
        description="The unique identifier for the muscle group",
        examples=[1]
    )
    name: str = Field(
        ...,
        max_length=20,
        description="The major muscle group name (e.g., Chest, Back, Legs)",
        examples=["Chest", "Back", "Legs"]
    )

    model_config = ConfigDict(from_attributes=True)


class MuscleResponse(BaseModel):
    id: int = Field(
        ...,
        description="The unique identifier for the individual muscle",
        examples=[1]
    )
    name: str = Field(
        ...,
        max_length=25,
        description="The specific muscle name (e.g., Biceps Brachii, Latissimus Dorsi)",
        examples=["Biceps", "Triceps", "Quads"]
    )
    image_url: str = Field(
        ...,
        description="Image hash showing the highlighted muscle (served by GET /v1/images/{hash})",
        examples=["3fa9c1d2e4b5a6978877665544332211ffeeddccbbaa99887766554433221100"]
    )

    model_config = ConfigDict(from_attributes=True)


class SingleExerciseDeltaResponse(ExerciseResponse):
    """
    action: 0: created, 1: updated, 2: deleted
    """
    action: int = Field(
        ...,
        description="An integer representing the type of change: 0 for created, 1 for updated, 2 for deleted",
        examples=[0, 1, 2]
    )


class ExerciseDeltaResponse(BaseModel):
    """
    Clients should treat created (0) and updated (1) as an upsert and ignore deletions (2) of unknown IDs,
    because a change can be delivered more than once.
    """
    updates: list[SingleExerciseDeltaResponse] = Field(
        ...,
        description="List of exercises that have been created, updated, or deleted since the last sync"
    )
    sync_time: str = Field(
        ...,
        description="Database timestamp of this response in ISO 8601 format. Pass it as last_sync_time for the next sync.",
        examples=["2024-06-01T18:30:00.123456+00:00"]
    )


class ExerciseListResponse(BaseModel):
    exercises: list[ExerciseResponse] = Field(
        ...,
        description="All non-deleted exercises that are verified or were created by the current user"
    )
    sync_time: str = Field(
        ...,
        description="Database timestamp of this response in ISO 8601 format. Pass it as last_sync_time to /exercises/delta for the next sync.",
        examples=["2024-06-01T18:30:00.123456+00:00"]
    )
