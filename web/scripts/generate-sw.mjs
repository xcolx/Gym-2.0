// Writes the service worker public/sw.js after `next build`: the precache manifest of this build in front of
// scripts/sw/routes.mjs and scripts/sw/worker.js. See "PWA" in ARCHITECTURE.md.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

import { pageEntry } from "./sw/routes.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const nextDir = join(root, ".next");
const publicDir = join(root, "public");
const OUTPUT = "sw.js";
/** Folders of public/ that are only cached once they're needed or in the background */
const LAZY_PUBLIC_DIRS = ["images"];

const readJson = (path) => JSON.parse(readFileSync(join(nextDir, path), "utf8"));

function filesIn(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? filesIn(path) : [path];
  });
}

/** The URL path of a file below `base`, every segment encoded like the browser does */
function urlPath(prefix, base, file) {
  return `${prefix}/${relative(base, file).split(sep).map(encodeURIComponent).join("/")}`;
}

const hash = (...parts) => {
  const digest = createHash("sha256");
  parts.forEach((part) => digest.update(part));
  return digest.digest("hex").slice(0, 16);
};

const buildId = readFileSync(join(nextDir, "BUILD_ID"), "utf8").trim();
const appRoutes = Object.values(readJson("app-path-routes-manifest.json"));
const appPaths = Object.entries(readJson("app-path-routes-manifest.json"));
const prerendered = readJson("prerender-manifest.json").routes;

// MARK: - Assets

// Without the source maps, only the developer tools load them
const staticAssets = filesIn(join(nextDir, "static"))
  .filter((file) => !file.endsWith(".map"))
  .map((file) => urlPath("/_next/static", join(nextDir, "static"), file));

const publicFiles = filesIn(publicDir).filter((file) => relative(publicDir, file) !== OUTPUT && !file.endsWith(".DS_Store"));
const isLazy = (file) => LAZY_PUBLIC_DIRS.some((dir) => relative(publicDir, file).split(sep)[0] === dir);
const publicAssets = publicFiles.filter((file) => !isLazy(file)).map((file) => urlPath("", publicDir, file));
const lazyFiles = publicFiles.filter(isLazy);

// Route handlers of files like /favicon.ico and /apple-icon.png (not /api or anything dynamic)
const metadataRoutes = appPaths
  .filter(([appPath, route]) => appPath.endsWith("/route") && /\.[a-z0-9]+$/i.test(route) && !route.includes("["))
  .map(([, route]) => route)
  .filter((route) => !route.startsWith("/api/"));

// MARK: - Pages

const pageRoutes = appPaths.filter(([appPath]) => appPath.endsWith("/page")).map(([, route]) => route);
const INTERNAL_PAGES = new Set(["/_not-found", "/_global-error"]);

const pages = [];
for (const route of pageRoutes) {
  if (INTERNAL_PAGES.has(route)) continue;
  const concrete = Object.entries(prerendered)
    .filter(([path, info]) => info.srcRoute === route && path !== route)
    .map(([path]) => path);
  // Prerendered with generateStaticParams: the known pages, like the server
  for (const path of concrete.length > 0 ? concrete : [route]) {
    const entry = pageEntry(path);
    if (entry) pages.push(entry);
    else console.warn(`generate-sw: ${route} can't be opened offline (catch-all segment)`);
  }
}

// MARK: - Output

const lazyUrls = lazyFiles.map((file) => urlPath("", publicDir, file));
const manifest = {
  buildId,
  version: "",
  assets: [...new Set([...staticAssets, ...publicAssets, ...metadataRoutes])].sort(),
  pages: pages.map(({ url, segments, params }) => ({ url, segments, params })),
  notFound: "/_not-found",
  lazy: { version: hash(...lazyFiles.map((file) => readFileSync(file))), urls: lazyUrls.sort() },
};

const routesSource = readFileSync(join(root, "scripts/sw/routes.mjs"), "utf8").replace(/^export /gm, "");
const workerSource = readFileSync(join(root, "scripts/sw/worker.js"), "utf8");
manifest.version = hash(buildId, JSON.stringify(manifest), routesSource, workerSource);

const output = [
  "// Generated by scripts/generate-sw.mjs from scripts/sw/routes.mjs and scripts/sw/worker.js, don't edit.",
  `const MANIFEST = ${JSON.stringify(manifest)};`,
  routesSource,
  workerSource,
].join("\n\n");
writeFileSync(join(publicDir, OUTPUT), output);

const size = (files) => files.reduce((sum, file) => sum + statSync(file).size, 0);
console.log(
  `generate-sw: public/${OUTPUT} (version ${manifest.version}): ${manifest.assets.length} assets, ${pages.length} pages, ` +
    `${lazyUrls.length} lazy files (${(size(lazyFiles) / 1e6).toFixed(1)} MB), ` +
    `${appRoutes.length} app routes`,
);
